//! The native build's hardware fragment: `hw-generic.config` cut down to the
//! drivers this machine actually uses.
//!
//! A native build runs on the rescue slot, whose kernel has exactly the
//! drivers in `hw-generic.config`. So the native fragment is always a subset
//! of it: every driver that bound to a device on this machine, plus the
//! symbols those drivers sit behind (vendor menus like `NET_VENDOR_INTEL`,
//! `BLK_DEV`, `VIRTIO`, libraries like `USB_USBNET`). Nothing is guessed:
//!
//! - which module drove each device comes from sysfs;
//! - which symbol builds which module comes from the kernel's Makefiles
//!   (`obj-$(CONFIG_X) += name.o`), the way `localmodconfig` finds it;
//! - what a symbol sits behind comes from walking the Kconfig tree from its
//!   root, following `source` and tracking `if` blocks and `depends on`.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

/// Module names of every driver bound to a device under `sys` (normally
/// `/sys`), on the buses a host's hardware is on. Dashes are written as
/// underscores, as the kernel does in module names.
pub fn bound_modules(sys: &Path) -> BTreeSet<String> {
    let mut found = BTreeSet::new();
    for bus in ["pci", "usb", "virtio"] {
        let Ok(devices) = fs::read_dir(sys.join("bus").join(bus).join("devices")) else { continue };
        for dev in devices.flatten() {
            let Ok(driver) = fs::canonicalize(dev.path().join("driver")) else { continue };
            // The module link names the module even when the driver is
            // registered under another name (xhci_hcd is in xhci_pci).
            let name = fs::canonicalize(driver.join("module"))
                .ok()
                .and_then(|m| m.file_name().map(|n| n.to_string_lossy().into_owned()))
                .or_else(|| driver.file_name().map(|n| n.to_string_lossy().into_owned()));
            if let Some(n) = name {
                found.insert(normalize(&n));
            }
        }
    }
    found
}

fn normalize(name: &str) -> String {
    name.replace('-', "_")
}

/// The native fragment, and a line per decision for the build log.
pub fn native_fragment(src: &Path, generic: &str, bound: &BTreeSet<String>) -> Result<(String, Vec<String>)> {
    let lines: Vec<(&str, &str)> = generic
        .lines()
        .filter_map(|l| {
            let sym = l.strip_prefix("CONFIG_")?.split_once('=')?.0;
            Some((sym, l))
        })
        .collect();
    let candidates: BTreeSet<&str> = lines.iter().map(|(s, _)| *s).collect();
    let modules = modules_by_symbol(src)?;
    let deps = kconfig_deps(src)?;

    let mut report = Vec::new();
    let mut keep: BTreeSet<&str> = BTreeSet::new();
    for sym in &candidates {
        let built = modules.get(*sym).map(|m| m.iter().filter(|n| bound.contains(*n)).collect::<Vec<_>>());
        if let Some(used) = built.filter(|u| !u.is_empty()) {
            report
                .push(format!("keep {sym}: drives {}", used.iter().map(|s| s.as_str()).collect::<Vec<_>>().join(", ")));
            keep.insert(sym);
        }
    }
    // What the kept drivers sit behind, as long as hw-generic names it.
    let mut queue: Vec<&str> = keep.iter().copied().collect();
    while let Some(sym) = queue.pop() {
        for dep in deps.get(sym).into_iter().flatten() {
            if let Some(c) = candidates.get(dep.as_str())
                && keep.insert(c)
            {
                report.push(format!("keep {c}: needed by {sym}"));
                queue.push(c);
            }
        }
    }
    for sym in &candidates {
        if !keep.contains(sym) {
            report.push(format!("drop {sym}: nothing on this machine uses it"));
        }
    }

    let mut out = String::from(
        "# Generated by neslina build from the devices this machine has: the lines\n\
         # of hw-generic.config whose drivers bound here, and what they need.\n",
    );
    for (sym, line) in &lines {
        if keep.contains(sym) {
            out.push_str(line);
            out.push('\n');
        }
    }
    Ok((out, report))
}

/// Every Makefile and Kbuild under `src`: symbol to the module names it builds.
fn modules_by_symbol(src: &Path) -> Result<BTreeMap<String, BTreeSet<String>>> {
    let mut map: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    let mut stack = vec![src.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = fs::read_dir(&dir) else { continue };
        for e in entries.flatten() {
            let path = e.path();
            let name = e.file_name();
            let name = name.to_string_lossy();
            if e.file_type().is_ok_and(|t| t.is_dir()) {
                if !name.starts_with('.') {
                    stack.push(path);
                }
            } else if name == "Makefile" || name == "Kbuild" {
                let text = fs::read_to_string(&path).unwrap_or_default().replace("\\\n", " ");
                for line in text.lines() {
                    let Some(rest) = line.trim_start().strip_prefix("obj-$(CONFIG_") else { continue };
                    let Some((sym, rhs)) = rest.split_once(')') else { continue };
                    let Some((_, objs)) = rhs.split_once('=') else { continue };
                    for obj in objs.split_whitespace() {
                        if let Some(m) = obj.strip_suffix(".o") {
                            map.entry(sym.to_owned()).or_default().insert(normalize(m));
                        }
                    }
                }
            }
        }
    }
    Ok(map)
}

/// Every symbol's dependencies: the symbols of the `if` blocks around it and
/// the plain conjuncts of its `depends on` lines. A `depends on` with `||`
/// or `!` in it says nothing a fragment could satisfy, and is skipped.
fn kconfig_deps(src: &Path) -> Result<BTreeMap<String, BTreeSet<String>>> {
    let mut deps: BTreeMap<String, BTreeSet<String>> = BTreeMap::new();
    walk(src, &src.join("Kconfig"), &mut Vec::new(), &mut deps).context("reading the Kconfig tree")?;
    Ok(deps)
}

fn symbols_of(expr: &str) -> Vec<String> {
    if expr.contains("||") || expr.contains('!') {
        return Vec::new();
    }
    expr.split("&&")
        .map(|t| t.trim().trim_matches(|c| c == '(' || c == ')').trim())
        .filter(|t| !t.is_empty() && t.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'))
        .filter(|t| t.bytes().any(|b| b.is_ascii_uppercase()))
        .map(str::to_owned)
        .collect()
}

fn walk(
    src: &Path,
    file: &Path,
    ifs: &mut Vec<Vec<String>>,
    deps: &mut BTreeMap<String, BTreeSet<String>>,
) -> Result<()> {
    let text = fs::read_to_string(file).with_context(|| format!("reading {}", file.display()))?;
    let depth = ifs.len();
    let mut current: Option<String> = None;
    for raw in text.lines() {
        let line = raw.trim();
        let word = line.split_whitespace().next().unwrap_or_default();
        match word {
            "config" | "menuconfig" => {
                let sym = line[word.len()..].trim().to_owned();
                let set = deps.entry(sym.clone()).or_default();
                set.extend(ifs.iter().flatten().cloned());
                current = Some(sym);
            }
            "depends" if line.starts_with("depends on") => {
                if let Some(sym) = &current {
                    let found = symbols_of(&line["depends on".len()..]);
                    deps.entry(sym.clone()).or_default().extend(found);
                }
            }
            "if" => {
                ifs.push(symbols_of(&line[2..]));
                current = None;
            }
            "endif" => {
                ifs.pop();
                current = None;
            }
            "source" | "rsource" | "osource" | "orsource" => {
                let arg = line[word.len()..].trim().trim_matches('"').replace("$(SRCARCH)", "x86");
                let base: PathBuf = if word.starts_with('r') || word == "orsource" {
                    file.parent().unwrap_or(src).to_path_buf()
                } else {
                    src.to_path_buf()
                };
                let target = base.join(&arg);
                // Globs and missing optional sources are not followed.
                if target.is_file() {
                    walk(src, &target, ifs, deps)?;
                }
                current = None;
            }
            "menu" | "endmenu" | "choice" | "endchoice" | "comment" | "mainmenu" => current = None,
            _ => {}
        }
    }
    ifs.truncate(depth);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tree(name: &str) -> tempdir::Dir {
        let d = tempdir::Dir::new(name);
        d.write("Kconfig", "source \"drivers/Kconfig\"\n");
        d.write(
            "drivers/Kconfig",
            "config PCI\n\tbool \"PCI\"\n\
             menuconfig NET_VENDOR_ACME\n\tbool \"Acme\"\n\
             if NET_VENDOR_ACME\n\
             config ACME_NIC\n\ttristate \"Acme NIC\"\n\tdepends on PCI && (LIBACME || !X)\n\
             config LIBACME\n\ttristate \"lib\"\n\
             config ACME_FAST\n\ttristate \"Acme fast\"\n\tdepends on PCI && LIBACME\n\
             endif\n\
             config OTHER\n\ttristate \"other\"\n",
        );
        d.write(
            "drivers/Makefile",
            "obj-$(CONFIG_ACME_NIC) += acme-nic.o\nobj-$(CONFIG_LIBACME) += libacme.o\n\
             obj-$(CONFIG_ACME_FAST) += acme_fast.o \\\n\tacme_fast_extra.o\nobj-$(CONFIG_OTHER) += other.o\n",
        );
        d
    }

    const GENERIC: &str =
        "CONFIG_NET_VENDOR_ACME=y\nCONFIG_ACME_NIC=y\nCONFIG_LIBACME=y\nCONFIG_ACME_FAST=y\nCONFIG_OTHER=y\n";

    #[test]
    fn keeps_bound_drivers_and_their_gates_only() {
        let d = tree("keeps");
        let bound: BTreeSet<String> = ["acme_nic".to_owned()].into();
        let (frag, report) = native_fragment(d.path(), GENERIC, &bound).unwrap();
        assert!(frag.contains("CONFIG_ACME_NIC=y"));
        assert!(frag.contains("CONFIG_NET_VENDOR_ACME=y"), "the if-block gate comes along");
        assert!(!frag.contains("CONFIG_LIBACME"), "an || dependency is not followed");
        assert!(!frag.contains("CONFIG_ACME_FAST") && !frag.contains("CONFIG_OTHER"));
        assert!(report.iter().any(|r| r == "drop OTHER: nothing on this machine uses it"));
    }

    #[test]
    fn follows_plain_depends_and_continued_makefile_lines() {
        let d = tree("follows");
        let bound: BTreeSet<String> = ["acme_fast_extra".to_owned()].into();
        let (frag, _) = native_fragment(d.path(), GENERIC, &bound).unwrap();
        assert!(frag.contains("CONFIG_ACME_FAST=y"));
        assert!(frag.contains("CONFIG_LIBACME=y"), "a plain && dependency comes along");
        assert!(frag.contains("CONFIG_NET_VENDOR_ACME=y"));
    }

    /// A throwaway directory under the test's own temp dir.
    mod tempdir {
        use std::path::{Path, PathBuf};

        pub struct Dir(PathBuf);

        impl Dir {
            pub fn new(name: &str) -> Self {
                let p = std::env::temp_dir().join(format!("neslina-{name}-{}", std::process::id()));
                let _ = std::fs::remove_dir_all(&p);
                std::fs::create_dir_all(&p).unwrap();
                Dir(p)
            }

            pub fn path(&self) -> &Path {
                &self.0
            }

            pub fn write(&self, rel: &str, text: &str) {
                let p = self.0.join(rel);
                std::fs::create_dir_all(p.parent().unwrap()).unwrap();
                std::fs::write(p, text).unwrap();
            }
        }

        impl Drop for Dir {
            fn drop(&mut self) {
                let _ = std::fs::remove_dir_all(&self.0);
            }
        }
    }
}
